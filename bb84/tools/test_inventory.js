/**
 * test_inventory.js — test envanteri (hakem bulgusu P1-5): "kaç test" sorusunun tek kaynaklı cevabı.
 *
 * Girdi: ci-reports/npm_test_summary.json (npm test'in koşu kaydı) ve bb84/reports/*.json (testlerin yazdığı raporlar).
 * Çıktı: docs/TEST_INVENTORY.md. Üç sayı birbirinden ayrılır:
 *   • runner item  — npm test'in koşturduğu süreç (bir test dosyası, bir --check denetimi, bir Python dosyası);
 *                    README'deki "N self-tests" budur.
 *   • check        — bir raporun içindeki tek tek doğrulamalar (checks[] dizisi); bir runner item birçok check içerir.
 *   • CI gate      — GitHub Actions'ta npm test DIŞINDA koşan kapılar (ör. mock_ibm_client.js'in 19 ETSI-014/mTLS testi).
 * Kullanım: node bb84/tools/test_inventory.js
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const sum = JSON.parse(fs.readFileSync(path.join(ROOT, "ci-reports", "npm_test_summary.json"), "utf8"));
const RDIR = path.join(ROOT, "bb84", "reports");
const reports = fs.readdirSync(RDIR).filter((f) => f.endsWith(".json")).sort();

let withChecks = 0, checksTotal = 0, checksPassed = 0;
const rows = [];
for (const f of reports) {
  let j; try { j = JSON.parse(fs.readFileSync(path.join(RDIR, f), "utf8")); } catch (_) { rows.push({ f, kind: "unreadable" }); continue; }
  if (Array.isArray(j.checks)) {
    const p = j.checks.filter((c) => c && (c.ok === true || c.pass === true || c.passed === true)).length;
    withChecks++; checksTotal += j.checks.length; checksPassed += p;
    rows.push({ f, kind: "checks", p, t: j.checks.length });
  } else rows.push({ f, kind: "other" });
}

const kinds = { check: 0, js: 0, py: 0, script: 0 };
for (const r of sum.results) {
  if (/--check$/.test(r.name)) kinds.check++;
  else if (/\.py/.test(r.name)) kinds.py++;
  else if (/\(.*\.sh\)$/.test(r.name)) kinds.script++;
  else kinds.js++;
}
const failed = sum.results.filter((r) => !r.ok).map((r) => r.name);

let md = `# Test inventory\n\nGenerated by \`node bb84/tools/test_inventory.js\` from \`ci-reports/npm_test_summary.json\` ` +
  `(run started ${sum.startedAt}, git HEAD \`${(sum.gitHead || "").slice(0, 7)}\`, tree ${sum.gitClean ? "clean" : `dirty (${sum.dirtyFiles} files)`}, ` +
  `core SHA-256 \`${(sum.coreSha256 || "").slice(0, 8)}…${(sum.coreSha256 || "").slice(-6)}\`) and \`bb84/reports/*.json\`.\n\n` +
  `**Simulation software tests.** They check this code against its own specification and a few published reference values; ` +
  `they are not hardware measurements.\n\n` +
  `## Three different counts\n\n` +
  `| Count | Value | Meaning |\n|---|---|---|\n` +
  `| Runner items (\`npm test\`) | ${sum.passed}/${sum.total} passed | processes the runner starts: ${kinds.check} sync checks (\`--check\`), ${kinds.js} JavaScript test/drill files, ${kinds.script} via shell script, ${kinds.py} Python HAL files. README's "self-tests" number is this one. |\n` +
  `| Checks inside reports | ${checksPassed}/${checksTotal} passed in ${withChecks} reports | individual assertions (\`checks[]\`) written by the tests to \`bb84/reports/\`. One runner item usually holds several checks. |\n` +
  `| Report files | ${reports.length} | \`bb84/reports/*.json\`; ${reports.length - withChecks} of them are measurement or campaign outputs without a \`checks[]\` array. Some are written by tools, not tests (for example \`ell_audit.json\`). |\n` +
  `| CI gate outside \`npm test\` | 19 | \`bb84/mock_ibm_client.js\` against a real KME process started in CI (gate 3b ephemeral) with **synthetic** keys (8 × 256 random bytes, step 4 of \`bb84/ci/run_integration_tests.sh\`). It tests the ETSI-014 + mTLS stack, not the QKD pipeline. The QKD → KME → TLS chain is tested by \`bb84/e2e_qkd_kme_tls_test.js\` (inside \`npm test\`). |\n\n` +
  (failed.length ? `Failed runner items in this run: ${failed.join(", ")}.\n\n` : "All runner items passed in this run.\n\n") +
  `## Runner items\n\n| # | Item | Result | Time (s) |\n|---|---|---|---|\n` +
  sum.results.map((r, i) => `| ${i + 1} | \`${r.name}\` | ${r.ok ? "pass" : `**fail** (exit ${r.code})`} | ${(r.ms / 1000).toFixed(1)} |`).join("\n") +
  `\n\n## Reports with checks\n\n| Report | Checks passed |\n|---|---|\n` +
  rows.filter((r) => r.kind === "checks").map((r) => `| \`${r.f}\` | ${r.p}/${r.t} |`).join("\n") +
  `\n\nReports without \`checks[]\`: ${rows.filter((r) => r.kind !== "checks").map((r) => `\`${r.f}\``).join(", ")}.\n`;
fs.writeFileSync(path.join(ROOT, "docs", "TEST_INVENTORY.md"), md);
console.log(`[test_inventory] runner ${sum.passed}/${sum.total}, checks ${checksPassed}/${checksTotal} in ${withChecks} reports, ${reports.length} report files → docs/TEST_INVENTORY.md`);
